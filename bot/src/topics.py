def format_nutrition_caption(story: dict[str, Any]) -> str:
    """Instagram caption = nutrition label for whatever Nib talks about."""
    n = story.get("nutrition") or {}
    item = story["item"].title() if story["item"] != "nothing" else "Sleep"
    serving = n.get("serving", "1 serving")
    lines = [
        f"{item} — nutrition",
        f"Serving: {serving}",
        f"{n.get('kcal', 0)} kcal",
        f"{n.get('protein_g', 0)}g protein · {n.get('carbs_g', 0)}g carbs · {n.get('fat_g', 0)}g fat",
    ]
    fiber = n.get("fiber_g")
    if fiber:
        lines.append(f"{fiber}g fiber")
    note = n.get("note")
    if note:
        lines.append(f"\n{note}")
    lines.append("\nFollow @nibthefridgegoblin")
    lines.append("#nutrition #fitness #fridgefinds #nibthefridgegoblin")
    return "\n".join(lines)


